-- Jalankan seluruh SQL ini di Supabase > SQL Editor.
create table if not exists public.class_items (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('tasks','materials','announcements','schedule')),
  title text not null,
  description text default '',
  subject text,
  due_date date,
  link text,
  is_archived boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.class_items enable row level security;

-- Semua pengunjung boleh membaca data kelas.
drop policy if exists "Public can read class items" on public.class_items;
create policy "Public can read class items"
on public.class_items for select
to anon, authenticated
using (true);

-- GANTI UUID_DI_SINI dengan User UID akun admin setelah akun dibuat di
-- Supabase > Authentication > Users. Hapus tanda kutip placeholder dan masukkan UUID.
-- Contoh: auth.uid() = '123e4567-e89b-12d3-a456-426614174000'::uuid
drop policy if exists "Only class admin can insert" on public.class_items;
create policy "Only class admin can insert"
on public.class_items for insert
to authenticated
with check (auth.uid() = 'UUID_DI_SINI'::uuid);

drop policy if exists "Only class admin can update" on public.class_items;
create policy "Only class admin can update"
on public.class_items for update
to authenticated
using (auth.uid() = 'UUID_DI_SINI'::uuid)
with check (auth.uid() = 'UUID_DI_SINI'::uuid);

drop policy if exists "Only class admin can delete" on public.class_items;
create policy "Only class admin can delete"
on public.class_items for delete
to authenticated
using (auth.uid() = 'UUID_DI_SINI'::uuid);
